// Hall tickets (with a QR code that verifies the ticket) and room seating charts.
import PDFDocument from 'pdfkit';
import QRCode from 'qrcode';
import { store } from './store.js';
import { ticketSignature } from './auth.js';

const NAVY = '#1f3864';

function header(doc, title) {
  const college = store.config.college || 'SRKR Engineering College (Autonomous), Bhimavaram';
  doc.fillColor(NAVY).fontSize(15).font('Helvetica-Bold').text(college.toUpperCase(), { align: 'center' });
  doc.moveDown(0.2).fontSize(10).font('Helvetica').fillColor('#333')
    .text(store.config.exam_cycle || 'Semester End Examinations', { align: 'center' });
  doc.moveDown(0.4).fontSize(13).font('Helvetica-Bold').fillColor(NAVY).text(title, { align: 'center' });
  doc.moveTo(40, doc.y + 6).lineTo(555, doc.y + 6).strokeColor(NAVY).lineWidth(1.5).stroke();
  doc.moveDown(1);
}

export async function hallTicket(roll, baseUrl, res) {
  const student = store.students.get(roll);
  const exams = store.examsOf(roll);
  const verifyUrl = `${baseUrl}/verify/${roll}?sig=${ticketSignature(roll)}`;
  const qr = await QRCode.toBuffer(verifyUrl, { margin: 1, width: 220 });

  const doc = new PDFDocument({ size: 'A4', margin: 40 });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `inline; filename="hall-ticket-${roll}.pdf"`);
  doc.pipe(res);
  header(doc, 'HALL TICKET');

  const top = doc.y;
  const rows = [['Roll number', roll], ['Name', student.name], ['Branch', student.branch],
    ['Year / Semester', `${student.year} / I`], ['Admission', student.admission_type],
    ['Regulation', store.config.regulation || 'R23']];
  doc.fontSize(10);
  rows.forEach(([k, v], i) => {
    doc.font('Helvetica-Bold').fillColor('#555').text(k, 40, top + i * 18, { width: 110 });
    doc.font('Helvetica').fillColor('#000').text(v, 150, top + i * 18, { width: 250 });
  });
  doc.rect(470, top - 4, 85, 100).strokeColor('#999').lineWidth(0.8).stroke();
  doc.fontSize(8).fillColor('#999').text('Photo', 470, top + 42, { width: 85, align: 'center' });
  doc.image(qr, 380, top - 4, { width: 80 });
  doc.fontSize(7).fillColor('#666').text('Scan to verify', 380, top + 78, { width: 80, align: 'center' });

  let y = top + rows.length * 18 + 20;
  const cols = [['Date', 62], ['Session', 70], ['Code', 62], ['Subject', 170], ['Type', 50], ['Room', 52], ['Seat', 49]];
  const drawRow = (cells, bold, fill) => {
    if (fill) doc.rect(40, y - 3, 515, 18).fill(fill);
    let x = 40;
    cells.forEach((c, i) => {
      doc.font(bold ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5).fillColor(bold ? '#fff' : '#000')
        .text(String(c ?? '-'), x + 3, y, { width: cols[i][1] - 6, height: 14, ellipsis: true });
      x += cols[i][1];
    });
    y += 18;
  };
  drawRow(cols.map((c) => c[0]), true, NAVY);
  exams.forEach((e, i) => drawRow([e.exam_date, `${e.session} ${e.time}`, e.subject_code, e.subject_name,
    e.reg_type === 'BACKLOG' ? 'Supply' : 'Regular', e.room_id, e.seat_no ? `${e.seat_no} (R${e.row} C${e.col})` : '-'],
  false, i % 2 ? '#f2f5fb' : null));

  y += 20;
  doc.font('Helvetica').fontSize(8.5).fillColor('#333');
  ['Report to the exam hall 30 minutes before the session starts.',
    'Carry this hall ticket and your college ID card. Electronic devices are not allowed.',
    'Sit only in the seat printed above. Seats are planned so neighbours write different papers.']
    .forEach((line) => { doc.text(`•  ${line}`, 40, y, { width: 515 }); y += 14; });
  doc.text('Controller of Examinations', 400, y + 40, { width: 155, align: 'center' });
  doc.fontSize(7).fillColor('#999').text('Generated by ExamGrid - demo data, not an official document', 40, 800,
    { width: 515, align: 'center' });
  doc.end();
}

export function roomChart(grid, res) {
  const { room, seats, date, session, time, invigilators } = grid;
  const doc = new PDFDocument({ size: 'A4', layout: 'landscape', margin: 30 });
  res.setHeader('Content-Type', 'application/pdf');
  res.setHeader('Content-Disposition', `inline; filename="room-${room.room_id}-${date}-${session}.pdf"`);
  doc.pipe(res);
  doc.fillColor(NAVY).fontSize(14).font('Helvetica-Bold')
    .text(`Seating chart - ${room.room_id} (${room.block}, floor ${room.floor})`, { align: 'center' });
  doc.fontSize(10).font('Helvetica').fillColor('#333')
    .text(`${date}  ${session} ${time}   |   ${seats.length} students   |   Invigilators: ${invigilators.map((d) => d.faculty_name).join(', ') || '-'}`,
      { align: 'center' });
  doc.fontSize(9).fillColor('#666').text('FRONT (board / invigilator desk)', { align: 'center' });

  const subjects = [...new Set(seats.map((s) => s.subject_code))].sort();
  const palette = ['#dbe8ff', '#ffe3c2', '#d6f5dd', '#f8d7e8', '#e6dcff', '#fff4b3', '#d0f0f5', '#f3e0d0'];
  const color = Object.fromEntries(subjects.map((s, i) => [s, palette[i % palette.length]]));
  const top = doc.y + 8, left = 40, w = (760 - 2 * 20) / room.cols, h = Math.min(52, (440 - 40) / room.rows);
  const at = new Map(seats.map((s) => [`${s.row},${s.col}`, s]));
  for (let r = 1; r <= room.rows; r++) {
    for (let c = 1; c <= room.cols; c++) {
      const x = left + (c - 1) * w, y = top + (r - 1) * h;
      const s = at.get(`${r},${c}`);
      doc.rect(x + 2, y + 2, w - 4, h - 4).fill(s ? color[s.subject_code] : '#f4f4f4');
      doc.rect(x + 2, y + 2, w - 4, h - 4).strokeColor('#bbb').lineWidth(0.5).stroke();
      doc.fillColor('#777').fontSize(6.5).text(`${(r - 1) * room.cols + c}`, x + 5, y + 5);
      if (s) {
        doc.fillColor('#000').font('Helvetica-Bold').fontSize(8).text(s.roll_no, x + 4, y + h / 2 - 9, { width: w - 8, align: 'center' });
        doc.font('Helvetica').fontSize(7).text(s.subject_code, x + 4, y + h / 2 + 2, { width: w - 8, align: 'center' });
      }
    }
  }
  let ly = top + room.rows * h + 12;
  doc.fontSize(8).fillColor('#000');
  subjects.forEach((sub, i) => {
    const x = left + (i % 4) * 190;
    if (i && i % 4 === 0) ly += 14;
    doc.rect(x, ly, 10, 10).fill(color[sub]);
    const n = seats.filter((s) => s.subject_code === sub).length;
    doc.fillColor('#000').text(`${sub}  ${store.subjects.get(sub)?.subject_name || ''} (${n})`, x + 14, ly + 1, { width: 175, ellipsis: true, height: 10 });
  });
  doc.end();
}
